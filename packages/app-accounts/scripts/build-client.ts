import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
const result = await build({
  entryPoints: ['src/client.ts'],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'browser',
  target: 'es2024',
  minify: true,
});
await writeFile(
  'src/client.generated.ts',
  `// Generated by scripts/build-client.ts.\nexport const CLIENT_JS = ${JSON.stringify(result.outputFiles[0].text)};\n`,
);
