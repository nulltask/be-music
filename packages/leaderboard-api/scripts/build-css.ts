// Compiles the Leaderboard pages' stylesheet (src/pages/app.css: Tailwind CSS v4 + Basecoat) and writes it into
// src/pages/styles.generated.ts, which the Worker bundles and serves. scripts/generate.ts runs it with the other
// generators; on its own:
//   pnpm --filter @be-music/leaderboard-api run build:css
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { binEntry } from './bin-entry.ts';

const packageDir = resolve(import.meta.dirname, '..');
const input = join(packageDir, 'src/pages/app.css');
const output = join(packageDir, 'src/pages/styles.generated.ts');
const workDir = mkdtempSync(join(tmpdir(), 'leaderboard-css-'));

try {
  const compiled = join(workDir, 'app.css');
  const tailwindcss = binEntry(packageDir, '@tailwindcss/cli', 'tailwindcss');
  execFileSync(process.execPath, [tailwindcss, '-i', input, '-o', compiled, '--minify'], {
    cwd: packageDir,
    stdio: 'inherit',
  });
  const css = readFileSync(compiled, 'utf8');
  const hash = createHash('sha256').update(css).digest('hex').slice(0, 12);
  writeFileSync(
    output,
    [
      '// Generated by scripts/build-css.ts from src/pages/app.css. Do not edit; run',
      '// `pnpm --filter @be-music/leaderboard-api run build:css` after changing classes in the pages.',
      `export const APP_CSS_HASH = '${hash}';`,
      `export const APP_CSS = ${JSON.stringify(css)};`,
      '',
    ].join('\n'),
  );
  console.log(`wrote ${output} (${css.length} bytes, ${hash})`);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
