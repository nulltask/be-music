// Builds the Leaderboard pages' icons from src/pages/icons/ and writes them into src/pages/icons.generated.ts, which
// the Worker bundles and serves. scripts/generate.ts runs it with the other generators; to change the icon, replace
// src/pages/icons/icon.svg and run:
//   pnpm --filter @be-music/leaderboard-api run build:icons
//
// icon.svg is the browser-tab icon as is. The PNGs (180 px for the iOS home screen, 192 / 512 px for the web app
// manifest) are rendered from it, and og.svg becomes the default 1200 x 630 share card, unless a hand-made file of that name sits next to it (apple-touch-icon.png,
// icon-192.png, icon-512.png) — small sizes often look better drawn by hand.
import { createHash } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { Resvg } from '@resvg/resvg-js';

const packageDir = resolve(import.meta.dirname, '..');
const iconsDir = join(packageDir, 'src/pages/icons');
const output = join(packageDir, 'src/pages/icons.generated.ts');
const svg = readFileSync(join(iconsDir, 'icon.svg'));

interface Icon {
  key: string;
  file: string;
  contentType: string;
  bytes: Buffer;
  size?: number;
}

function png(key: string, file: string, size: number): Icon {
  const handMade = join(iconsDir, file);
  const bytes = existsSync(handMade)
    ? readFileSync(handMade)
    : Buffer.from(new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render().asPng());
  return { key, file, contentType: 'image/png', bytes, size };
}

const icons: Icon[] = [
  { key: 'favicon', file: 'icon.svg', contentType: 'image/svg+xml', bytes: svg },
  png('appleTouch', 'apple-touch-icon.png', 180),
  png('manifest192', 'icon-192.png', 192),
  png('manifest512', 'icon-512.png', 512),
  // The default share card (1200 x 630) of link previews, from og.svg (an og.png next to it overrides it).
  card(),
];

function card(): Icon {
  const handMade = join(iconsDir, 'og.png');
  const bytes = existsSync(handMade)
    ? readFileSync(handMade)
    : Buffer.from(
        new Resvg(readFileSync(join(iconsDir, 'og.svg')), {
          fitTo: { mode: 'width', value: 1200 },
          font: { loadSystemFonts: true, defaultFontFamily: 'Helvetica' },
        })
          .render()
          .asPng(),
      );
  return { key: 'ogDefault', file: 'og.png', contentType: 'image/png', bytes, size: 1200 };
}

const entries = icons.map((icon) => {
  const hash = createHash('sha256').update(icon.bytes).digest('hex').slice(0, 12);
  const [stem, extension] = [icon.file.replace(/\.[^.]+$/, ''), icon.file.split('.').pop()];
  return [
    `  ${icon.key}: {`,
    `    path: '/assets/${stem}.${hash}.${extension}',`,
    `    contentType: '${icon.contentType}',`,
    ...(icon.size !== undefined ? [`    size: ${icon.size},`] : []),
    `    base64: '${icon.bytes.toString('base64')}',`,
    '  },',
  ].join('\n');
});

writeFileSync(
  output,
  [
    '// Generated by scripts/build-icons.ts from src/pages/icons/. Do not edit; replace the icon there and run',
    '// `pnpm --filter @be-music/leaderboard-api run build:icons`.',
    'export const ICONS = {',
    ...entries,
    '} as const;',
    '',
  ].join('\n'),
);
console.log(`wrote ${output} (${icons.map((icon) => `${icon.file} ${icon.bytes.length} B`).join(', ')})`);
