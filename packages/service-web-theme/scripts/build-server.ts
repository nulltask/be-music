// Resolve Lit's Node implementation once at build time. Workers must not import its browser DOM implementation.
import { build } from 'esbuild';
import { writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';

const packageDir = resolve(import.meta.dirname, '..');
const output = resolve(packageDir, 'src/server.generated.ts');
const result = await build({
  entryPoints: [resolve(packageDir, 'src/server.ts')],
  bundle: true,
  write: false,
  format: 'esm',
  platform: 'node',
  conditions: ['node'],
  target: 'es2024',
  minify: true,
  legalComments: 'inline',
  metafile: true,
  plugins: [
    {
      name: 'worker-node-builtins',
      setup(builder) {
        builder.onResolve({ filter: /^buffer$/ }, () => ({ path: 'node:buffer', external: true }));
      },
    },
  ],
});
const imports = Object.values(result.metafile!.outputs).flatMap((entry) =>
  entry.imports.filter((item) => item.external),
);
if (imports.some((entry) => entry.path !== 'node:buffer'))
  throw new Error(`Unexpected Lit SSR runtime imports: ${imports.map((entry) => entry.path).join(', ')}`);
const source = result.outputFiles[0]!.text;
await writeFile(
  output,
  `// @ts-nocheck\n// Generated by scripts/build-server.ts. Requires Workers nodejs_compat.\n${source}`,
);
console.log(`wrote ${output} (${source.length} bytes)`);
