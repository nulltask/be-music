// Compiles the Accounts and Dashboard stylesheet (src/theme.css: Tailwind CSS v4 + Basecoat) and writes it into
// src/styles.generated.ts, which those Workers inline. `prepare` runs it; on its own:
//   pnpm --filter @be-music/service-web-theme run build:css
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { binEntry } from './bin-entry.ts';

const packageDir = resolve(import.meta.dirname, '..');
const input = join(packageDir, 'src/theme.css');
const output = join(packageDir, 'src/styles.generated.ts');
const workDir = mkdtempSync(join(tmpdir(), 'service-theme-css-'));

try {
  const compiled = join(workDir, 'theme.css');
  const tailwindcss = binEntry(packageDir, '@tailwindcss/cli', 'tailwindcss');
  execFileSync(process.execPath, [tailwindcss, '-i', input, '-o', compiled, '--minify'], {
    cwd: packageDir,
    stdio: 'inherit',
  });
  const css = withSystemDarkTokens(readFileSync(compiled, 'utf8'));
  if (!css.includes('.btn{')) throw new Error('compiled CSS has no Basecoat button styles');
  writeFileSync(
    output,
    [
      '// Generated by scripts/build-css.ts from src/theme.css. Do not edit; run',
      '// `pnpm --filter @be-music/service-web-theme run build:css` after changing classes.',
      `export const SERVICE_CSS = ${JSON.stringify(css)};`,
      '',
    ].join('\n'),
  );
  console.log(`wrote ${output} (${css.length} bytes)`);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}

/**
 * Basecoat stores its dark palette on `.dark`. These pages cannot add that class: their content security policy
 * blocks inline scripts. Repeat the token block for the system color scheme. `dark:` utilities are already compiled
 * against that media query (`src/theme.css`).
 */
function withSystemDarkTokens(css: string): string {
  const match = /\.dark\{(--background:[^}]*)\}/.exec(css);
  if (match === null) throw new Error('compiled CSS has no Basecoat .dark token block');
  return `${css}@media (prefers-color-scheme:dark){:root{${match[1]}}}`;
}
