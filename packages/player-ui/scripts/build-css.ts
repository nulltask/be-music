// Compiles the Basecoat theme's stylesheet (src/themes/basecoat.css: Tailwind CSS v4 + Basecoat) into
// src/themes/basecoat.generated.ts, which `themes/basecoat.ts` adds to the elements' shadow roots.
//   pnpm --filter @be-music/player-ui run build:css
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { binEntry } from './bin-entry.ts';

const packageDir = resolve(import.meta.dirname, '..');
const input = join(packageDir, 'src/themes/basecoat.css');
const output = join(packageDir, 'src/themes/basecoat.generated.ts');
const workDir = mkdtempSync(join(tmpdir(), 'basecoat-theme-'));

try {
  const compiled = join(workDir, 'basecoat.css');
  const tailwindcss = binEntry(packageDir, '@tailwindcss/cli', 'tailwindcss');
  execFileSync(process.execPath, [tailwindcss, '-i', input, '-o', compiled, '--minify'], {
    cwd: packageDir,
    stdio: 'inherit',
  });
  const css = readFileSync(compiled, 'utf8');
  if (!css.includes('.btn{')) throw new Error('compiled CSS has no Basecoat button styles');
  writeFileSync(
    output,
    [
      '// Generated by scripts/build-css.ts from src/themes/basecoat.css. Do not edit.',
      `export const BASECOAT_THEME_CSS = ${JSON.stringify(css)};`,
      '',
    ].join('\n'),
  );
  console.log(`wrote ${output} (${css.length} bytes)`);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
