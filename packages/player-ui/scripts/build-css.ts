// Compiles the preview screens' stylesheet (src/styles/preview.css: Tailwind CSS v4 + Basecoat) into
// src/styles/preview-theme.generated.ts, which the Lit components adopt in their shadow roots.
//   pnpm --filter @be-music/player-ui run build:css
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { binEntry } from './bin-entry.ts';

const packageDir = resolve(import.meta.dirname, '..');
const input = join(packageDir, 'src/styles/preview.css');
const output = join(packageDir, 'src/styles/preview-theme.generated.ts');
const workDir = mkdtempSync(join(tmpdir(), 'preview-theme-'));

try {
  const compiled = join(workDir, 'preview.css');
  const tailwindcss = binEntry(packageDir, '@tailwindcss/cli', 'tailwindcss');
  execFileSync(process.execPath, [tailwindcss, '-i', input, '-o', compiled, '--minify'], {
    cwd: packageDir,
    stdio: 'inherit',
  });
  const css = readFileSync(compiled, 'utf8');
  if (!css.includes('.btn{')) throw new Error('compiled CSS has no Basecoat button styles');
  writeFileSync(
    output,
    [
      '// Generated by scripts/build-css.ts from src/styles/preview.css. Do not edit.',
      `export const PREVIEW_THEME_CSS = ${JSON.stringify(css)};`,
      '',
    ].join('\n'),
  );
  console.log(`wrote ${output} (${css.length} bytes)`);
} finally {
  rmSync(workDir, { recursive: true, force: true });
}
