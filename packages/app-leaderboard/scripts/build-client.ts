// Bundles the pages' client script (client/main.ts: passkey sign-in, settings page) and writes it into
// src/pages/client.generated.ts, which the Worker bundles and serves. scripts/generate.ts runs it with the other
// generators; on its own:
//   pnpm --filter @be-music/app-leaderboard run build:client
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { build } from 'esbuild';

const packageDir = resolve(import.meta.dirname, '..');
const output = join(packageDir, 'src/pages/client.generated.ts');

const result = await build({
  entryPoints: [join(packageDir, 'client/main.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: 'es2020',
  legalComments: 'none',
  write: false,
});
const js = result.outputFiles[0]!.text;
const hash = createHash('sha256').update(js).digest('hex').slice(0, 12);
writeFileSync(
  output,
  [
    '// Generated by scripts/build-client.ts from client/. Do not edit; run',
    '// `pnpm --filter @be-music/app-leaderboard run build:client` after changing the client script.',
    `export const CLIENT_JS_HASH = '${hash}';`,
    `export const CLIENT_JS = ${JSON.stringify(js)};`,
    '',
  ].join('\n'),
);
console.log(`wrote ${output} (${js.length} bytes, ${hash})`);
