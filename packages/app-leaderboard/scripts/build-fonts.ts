// Copies the share card's Latin typeface (Inter Tight, variable weight, Latin subset; SIL OFL 1.1) out of
// @fontsource-variable/inter-tight and writes it into src/pages/fonts.generated.ts, which the Worker bundles and
// serves. scripts/generate.ts runs it with the other generators; on its own:
//   pnpm --filter @be-music/app-leaderboard run build:fonts
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';

const packageDir = resolve(import.meta.dirname, '..');
const output = join(packageDir, 'src/pages/fonts.generated.ts');
const require = createRequire(join(packageDir, 'package.json'));
const fontsource = dirname(require.resolve('@fontsource-variable/inter-tight/package.json'));
const bytes = readFileSync(join(fontsource, 'files/inter-tight-latin-wght-normal.woff2'));
const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);

writeFileSync(
  output,
  [
    '// Generated by scripts/build-fonts.ts from @fontsource-variable/inter-tight. Do not edit.',
    'export const FONTS = {',
    '  interTight: {',
    "    family: 'Inter Tight',",
    `    path: '/assets/inter-tight.${hash}.woff2',`,
    "    contentType: 'font/woff2',",
    `    base64: '${bytes.toString('base64')}',`,
    '  },',
    '} as const;',
    '',
  ].join('\n'),
);
console.log(`wrote ${output} (inter-tight ${bytes.length} B)`);
